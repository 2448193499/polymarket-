# Falcon sync (keep English) -> utils/polymarket_live.js
$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $MyInvocation.MyCommand.Path
$secFile = Join-Path $root "secrets\local.json"
$outJs = Join-Path $root "utils\polymarket_live.js"
$rawOut = Join-Path $root "utils\falcon_raw.json"

function Truncate-Label([string]$s, [int]$max = 12) {
  if ([string]::IsNullOrEmpty($s)) { return $s }
  if ($s.Length -le $max) { return $s }
  return $s.Substring(0, $max)
}

if (-not (Test-Path -LiteralPath $secFile)) { Write-Host "missing secrets"; exit 1 }
$sec = Get-Content -LiteralPath $secFile -Raw -Encoding UTF8 | ConvertFrom-Json
$token = $sec.falconBearer
if (-not $token) { Write-Host "empty token"; exit 1 }

Write-Host "1/2 Falcon fetch..."
$body = (@{
  agent_id = 574
  params = @{ closed = "False"; min_volume = "1000" }
  pagination = @{ limit = 50; offset = 0 }
  formatter_config = @{ format_type = "raw" }
} | ConvertTo-Json -Compress -Depth 6)

$resp = Invoke-RestMethod -Method Post `
  -Uri "https://narrative.agent.heisenberg.so/api/v2/semantic/retrieve/parameterized" `
  -Headers @{ Authorization = "Bearer $token"; "Content-Type" = "application/json" } `
  -Body $body -TimeoutSec 60

$resp | ConvertTo-Json -Depth 10 | Set-Content -LiteralPath $rawOut -Encoding UTF8
$results = @($resp.data.results)
if (-not $results.Count) { Write-Host "0 results"; exit 1 }

$sorted = $results | Sort-Object { [double]($_.volume_total) } -Descending
Write-Host ("2/2 write EN markets, n=" + $sorted.Count)

$markets = New-Object System.Collections.Generic.List[object]
$i = 0
foreach ($m in $sorted) {
  if (-not $m.question) { continue }
  $red = if ($m.side_a_outcome) { [string]$m.side_a_outcome } else { "Yes" }
  $blue = if ($m.side_b_outcome) { [string]$m.side_b_outcome } else { "No" }
  $vol = 0.0
  try { $vol = [double]$m.volume_total } catch {}
  $bodyEn = "Synced from Falcon/Polymarket (active). slug: $($m.slug). Approx volume $([math]::Round($vol,0)). Stance and comments only; no betting."

  Write-Host ("  - " + [string]$m.question)
  $markets.Add([ordered]@{
    externalId = [string]$m.condition_id
    title = [string]$m.question
    body = $bodyEn
    redLabel = Truncate-Label $red 12
    blueLabel = Truncate-Label $blue 12
    redCount = 40 + ($i % 20)
    blueCount = 60 - ($i % 20)
    slug = [string]$m.slug
    endDate = [string]$m.end_date
    volume = $vol
  })
  $i++
  if ($markets.Count -ge 50) { break }
}

$marketsJson = ($markets.ToArray() | ConvertTo-Json -Depth 6)
$syncedAt = [DateTimeOffset]::Now.ToUnixTimeMilliseconds()
$content = @"
/** auto-generated by sync-falcon.ps1 (English original) */
module.exports = {
  syncedAt: $syncedAt,
  source: "falcon",
  markets: $marketsJson
}
"@
[System.IO.File]::WriteAllText($outJs, $content, [System.Text.UTF8Encoding]::new($false))
Write-Host ("OK count=" + $markets.Count)